/**
 * generate-sql-import.js
 * Membaca content/materi/kelas-*.json dan menghasilkan file SQL yang
 * bisa langsung di-paste ke Supabase SQL Editor.
 *
 * Strategi aman (no duplicate key):
 *   - UPDATE rows yang sudah ada di DB (match by grade + title)
 *   - INSERT ONLY rows yang benar-benar baru (belum ada by grade + title)
 *   - Questions: INSERT WHERE NOT EXISTS (body match)
 *
 * Jalankan:  node scripts/generate-sql-import.js
 * Output  :  database/import_materi_generated.sql
 */

import fs  from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname  = path.dirname(__filename);

const CONTENT_DIR = path.join(__dirname, '..', 'content', 'materi');
const OUT_FILE    = path.join(__dirname, '..', 'database', 'import_materi_generated.sql');

// ── helpers ───────────────────────────────────────────────────────────────────

function sq(str) {
  if (str == null) return 'NULL';
  return `'${String(str).replace(/'/g, "''")}'`;
}

function jsonSq(val) {
  if (val == null) return 'NULL';
  return `'${JSON.stringify(val).replace(/'/g, "''")}'::jsonb`;
}

// ── collect files ─────────────────────────────────────────────────────────────

const files = fs.readdirSync(CONTENT_DIR)
  .filter(f => f.startsWith('kelas-') && f.endsWith('.json'))
  .sort();

if (files.length === 0) {
  console.error('❌ Tidak ada file kelas-*.json di', CONTENT_DIR);
  process.exit(1);
}

const lines = [];

lines.push('-- =================================================================');
lines.push('-- import_materi_generated.sql  (B3Matika)');
lines.push('-- Auto-generated by scripts/generate-sql-import.js');
lines.push(`-- Generated: ${new Date().toISOString()}`);
lines.push('--');
lines.push('-- CARA PAKAI:');
lines.push('-- 1. Supabase Dashboard → SQL Editor → New query');
lines.push('-- 2. Paste seluruh isi file ini → klik RUN');
lines.push('--');
lines.push('-- STRATEGI AMAN:');
lines.push('-- • UPDATE  : topik yg sudah ada (cocok grade + title) → tambah slug & konten');
lines.push('-- • INSERT  : hanya topik yg benar-benar baru (WHERE NOT EXISTS)');
lines.push('-- • Questions: INSERT WHERE NOT EXISTS body (tidak timpa soal lama)');
lines.push('-- • Tidak ada DROP / DELETE / TRUNCATE sama sekali');
lines.push('-- =================================================================');
lines.push('');
lines.push('BEGIN;');
lines.push('');

// ── STEP 1: Tambah kolom ──────────────────────────────────────────────────────
lines.push('-- ─────────────────────────────────────────────────────────────────');
lines.push('-- STEP 1: Tambah kolom baru ke topics & questions (idempotent)');
lines.push('-- ─────────────────────────────────────────────────────────────────');
lines.push('');
lines.push('ALTER TABLE public.topics');
lines.push('  ADD COLUMN IF NOT EXISTS slug             VARCHAR(100),');
lines.push('  ADD COLUMN IF NOT EXISTS sort_order       SMALLINT,');
lines.push('  ADD COLUMN IF NOT EXISTS summary          TEXT,');
lines.push('  ADD COLUMN IF NOT EXISTS objectives       JSONB,');
lines.push('  ADD COLUMN IF NOT EXISTS examples         JSONB,');
lines.push('  ADD COLUMN IF NOT EXISTS common_mistakes  JSONB,');
lines.push('  ADD COLUMN IF NOT EXISTS videos           JSONB;');
lines.push('');
lines.push('ALTER TABLE public.questions');
lines.push('  ADD COLUMN IF NOT EXISTS explanation  TEXT,');
lines.push('  ADD COLUMN IF NOT EXISTS points       SMALLINT DEFAULT 1;');
lines.push('');
lines.push('-- Indeks parsial (grade, slug) ─ hanya untuk baris yg punya slug');
lines.push('CREATE UNIQUE INDEX IF NOT EXISTS idx_topics_grade_slug');
lines.push('  ON public.topics (grade, slug)');
lines.push('  WHERE slug IS NOT NULL;');
lines.push('');
lines.push('CREATE INDEX IF NOT EXISTS idx_topics_grade_sort');
lines.push('  ON public.topics (grade, sort_order);');
lines.push('');

// ── Baca semua topik ──────────────────────────────────────────────────────────
let totalTopics = 0;
let totalQues   = 0;
const allTopics = [];

for (const file of files) {
  let topics;
  try {
    topics = JSON.parse(fs.readFileSync(path.join(CONTENT_DIR, file), 'utf-8'));
  } catch (e) {
    console.error(`❌ JSON tidak valid: ${file}: ${e.message}`);
    process.exit(1);
  }
  for (const t of topics) {
    totalTopics++;
    allTopics.push(t);
  }
}

// ── STEP 2: UPDATE topik yang sudah ada (match by grade + title) ──────────────
lines.push('-- ─────────────────────────────────────────────────────────────────');
lines.push('-- STEP 2: UPDATE topik yang sudah ada di DB (match grade + title)');
lines.push('--         Menambah slug, sort_order, summary, dan konten baru.');
lines.push('--         Tidak mengubah id, tidak menghapus apa pun.');
lines.push('-- ─────────────────────────────────────────────────────────────────');
lines.push('');

for (const t of allTopics) {
  lines.push(`-- UPDATE Kelas ${t.grade}: ${t.title}`);
  lines.push(`UPDATE public.topics SET`);
  lines.push(`  slug            = ${sq(t.slug)},`);
  lines.push(`  sort_order      = ${t.sort_order ?? 'NULL'},`);
  lines.push(`  summary         = ${sq(t.summary)},`);
  lines.push(`  content         = ${sq(t.content)},`);
  lines.push(`  objectives      = ${jsonSq(t.objectives)},`);
  lines.push(`  examples        = ${jsonSq(t.examples)},`);
  lines.push(`  common_mistakes = ${jsonSq(t.common_mistakes)},`);
  lines.push(`  videos          = ${jsonSq(t.videos)}`);
  lines.push(`WHERE grade = ${t.grade}`);
  lines.push(`  AND title = ${sq(t.title)};`);
  lines.push('');
}

// ── STEP 3: INSERT topik benar-benar baru (WHERE NOT EXISTS) ──────────────────
lines.push('-- ─────────────────────────────────────────────────────────────────');
lines.push('-- STEP 3: INSERT topik baru (yang belum ada di DB sama sekali)');
lines.push('--         WHERE NOT EXISTS mencegah duplicate key error.');
lines.push('-- ─────────────────────────────────────────────────────────────────');
lines.push('');

for (const t of allTopics) {
  lines.push(`-- INSERT baru Kelas ${t.grade}: ${t.title} (skip jika sudah ada)`);
  lines.push(`INSERT INTO public.topics`);
  lines.push(`  (grade, slug, title, sort_order, summary, content, objectives, examples, common_mistakes, videos)`);
  lines.push(`SELECT`);
  lines.push(`  ${t.grade}, ${sq(t.slug)}, ${sq(t.title)}, ${t.sort_order ?? 'NULL'},`);
  lines.push(`  ${sq(t.summary)}, ${sq(t.content)},`);
  lines.push(`  ${jsonSq(t.objectives)}, ${jsonSq(t.examples)},`);
  lines.push(`  ${jsonSq(t.common_mistakes)}, ${jsonSq(t.videos)}`);
  lines.push(`WHERE NOT EXISTS (`);
  lines.push(`  SELECT 1 FROM public.topics`);
  lines.push(`  WHERE grade = ${t.grade} AND title = ${sq(t.title)}`);
  lines.push(`);`);
  lines.push('');
}

// ── STEP 4: INSERT questions ──────────────────────────────────────────────────
lines.push('-- ─────────────────────────────────────────────────────────────────');
lines.push('-- STEP 4: INSERT questions (WHERE NOT EXISTS ─ tidak timpa soal lama)');
lines.push('-- ─────────────────────────────────────────────────────────────────');
lines.push('');

for (const t of allTopics) {
  if (!t.questions || t.questions.length === 0) continue;
  lines.push(`-- Soal Kelas ${t.grade}: ${t.title}`);
  for (const q of t.questions) {
    totalQues++;
    lines.push(`INSERT INTO public.questions (topic_id, body, options, answer, explanation, points)`);
    lines.push(`SELECT t.id, ${sq(q.body)}, ${jsonSq(q.options)}, ${q.answer ?? 0}, ${sq(q.explanation ?? null)}, ${q.points ?? 1}`);
    lines.push(`FROM   public.topics t`);
    lines.push(`WHERE  t.grade = ${t.grade} AND t.title = ${sq(t.title)}`);
    lines.push(`  AND  NOT EXISTS (`);
    lines.push(`    SELECT 1 FROM public.questions qq`);
    lines.push(`    WHERE qq.topic_id = t.id AND qq.body = ${sq(q.body)}`);
    lines.push(`  );`);
  }
  lines.push('');
}

// ── STEP 5: Perbaiki sort_order lama ─────────────────────────────────────────
lines.push('-- ─────────────────────────────────────────────────────────────────');
lines.push('-- STEP 5: Set sort_order default untuk topik lama yang belum diset');
lines.push('-- ─────────────────────────────────────────────────────────────────');
lines.push('');
lines.push('UPDATE public.topics SET sort_order = id WHERE sort_order IS NULL;');
lines.push('');

lines.push('COMMIT;');
lines.push('');
lines.push('-- ─────────────────────────────────────────────────────────────────');
lines.push('-- Verifikasi (jalankan setelah COMMIT di query baru):');
lines.push('-- SELECT grade, count(*) AS topik,');
lines.push('--        count(slug) AS punya_slug,');
lines.push('--        (SELECT count(*) FROM questions q WHERE q.topic_id IN');
lines.push('--         (SELECT id FROM topics t2 WHERE t2.grade = topics.grade)) AS soal');
lines.push('-- FROM topics GROUP BY grade ORDER BY grade;');
lines.push('-- ─────────────────────────────────────────────────────────────────');

// ── tulis file ────────────────────────────────────────────────────────────────
const outDir = path.dirname(OUT_FILE);
if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(OUT_FILE, lines.join('\n'), 'utf-8');

const sizeKb = (fs.statSync(OUT_FILE).size / 1024).toFixed(1);
console.log(`\n✅ File SQL berhasil dibuat:`);
console.log(`   ${OUT_FILE}`);
console.log(`   Ukuran : ${sizeKb} KB`);
console.log(`   Topik  : ${totalTopics}`);
console.log(`   Soal   : ${totalQues}`);
console.log(``);
console.log(`📋 CARA PAKAI:`);
console.log(`   1. Supabase Dashboard → SQL Editor → New query`);
console.log(`   2. Buka file di atas → Select All → Copy → Paste → RUN`);
console.log(`   3. Tunggu: "Success. No rows returned."`);
