/**
 * generate-sql-import.js
 * Membaca content/materi/kelas-*.json dan menghasilkan file SQL yang
 * bisa langsung di-paste ke Supabase SQL Editor.
 *
 * Jalankan:  node scripts/generate-sql-import.js
 * Output  :  database/import_materi_generated.sql
 */

import fs   from 'fs';
import path  from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname  = path.dirname(__filename);

const CONTENT_DIR = path.join(__dirname, '..', 'content', 'materi');
const OUT_FILE    = path.join(__dirname, '..', 'database', 'import_materi_generated.sql');

// ── helpers ──────────────────────────────────────────────────────────────────

/** Escape single-quotes untuk SQL string literal */
function sq(str) {
  if (str == null) return 'NULL';
  return `'${String(str).replace(/'/g, "''")}'`;
}

/** Serialize ke JSON-safe SQL string */
function jsonSq(val) {
  if (val == null) return 'NULL';
  return `'${JSON.stringify(val).replace(/'/g, "''")}'::jsonb`;
}

// ── collect files ─────────────────────────────────────────────────────────────

const files = fs.readdirSync(CONTENT_DIR)
  .filter(f => f.startsWith('kelas-') && f.endsWith('.json'))
  .sort();

if (files.length === 0) {
  console.error('❌ Tidak ada file kelas-*.json di', CONTENT_DIR);
  process.exit(1);
}

const lines = [];
lines.push('-- ============================================================');
lines.push('-- import_materi_generated.sql  (B3Matika)');
lines.push('-- Auto-generated by scripts/generate-sql-import.js');
lines.push(`-- Generated: ${new Date().toISOString()}`);
lines.push('--');
lines.push('-- CARA PAKAI:');
lines.push('-- 1. Buka https://supabase.com > project kamu > SQL Editor');
lines.push('-- 2. Buat query baru → Paste seluruh isi file ini → Run');
lines.push('-- 3. Tunggu sampai selesai, tidak ada rollback karena UPSERT aman.');
lines.push('--');
lines.push('-- CATATAN KEAMANAN:');
lines.push('-- • Tidak ada DROP, DELETE, atau TRUNCATE.');
lines.push('-- • Semua operasi pakai ON CONFLICT DO UPDATE (UPSERT).');
lines.push('-- • question_solves dan attempts tidak disentuh sama sekali.');
lines.push('-- ============================================================');
lines.push('');
lines.push('BEGIN;');
lines.push('');

// ── STEP 1: Tambah kolom baru ke tabel topics ─────────────────────────────────
lines.push('-- ─────────────────────────────────────────────────────────────');
lines.push('-- STEP 1: Tambah kolom baru (idempotent, aman bila sudah ada)');
lines.push('-- ─────────────────────────────────────────────────────────────');
lines.push('');
lines.push('ALTER TABLE public.topics');
lines.push('  ADD COLUMN IF NOT EXISTS slug             VARCHAR(100),');
lines.push('  ADD COLUMN IF NOT EXISTS sort_order       SMALLINT,');
lines.push('  ADD COLUMN IF NOT EXISTS summary          TEXT,');
lines.push('  ADD COLUMN IF NOT EXISTS objectives       JSONB,');
lines.push('  ADD COLUMN IF NOT EXISTS examples         JSONB,');
lines.push('  ADD COLUMN IF NOT EXISTS common_mistakes  JSONB,');
lines.push('  ADD COLUMN IF NOT EXISTS videos           JSONB;');
lines.push('');

lines.push('ALTER TABLE public.questions');
lines.push('  ADD COLUMN IF NOT EXISTS explanation  TEXT,');
lines.push('  ADD COLUMN IF NOT EXISTS points       SMALLINT DEFAULT 1;');
lines.push('');

lines.push('-- Indeks unik parsial pada (grade, slug)');
lines.push('CREATE UNIQUE INDEX IF NOT EXISTS idx_topics_grade_slug');
lines.push('  ON public.topics (grade, slug)');
lines.push('  WHERE slug IS NOT NULL;');
lines.push('');
lines.push('CREATE INDEX IF NOT EXISTS idx_topics_grade_sort');
lines.push('  ON public.topics (grade, sort_order);');
lines.push('');

// ── STEP 2: UPSERT topics ────────────────────────────────────────────────────
lines.push('-- ─────────────────────────────────────────────────────────────');
lines.push('-- STEP 2: UPSERT topics (slug menjadi identifier unik per grade)');
lines.push('-- ─────────────────────────────────────────────────────────────');
lines.push('');

let totalTopics   = 0;
let totalQuestions = 0;

const allTopics = [];

for (const file of files) {
  const filePath = path.join(CONTENT_DIR, file);
  let topics;
  try {
    topics = JSON.parse(fs.readFileSync(filePath, 'utf-8'));
  } catch (e) {
    console.error(`❌ JSON tidak valid: ${file}: ${e.message}`);
    process.exit(1);
  }

  lines.push(`-- == ${file} (${topics.length} topik) ==`);

  for (const t of topics) {
    totalTopics++;
    // Coba match title ke tabel existing (berdasarkan grade + title)
    // Kalau tidak match, INSERT baru. Kita pakai slug sebagai key.

    const slugSql       = sq(t.slug);
    const gradeSql      = t.grade;
    const titleSql      = sq(t.title);
    const sortSql       = t.sort_order != null ? t.sort_order : 'NULL';
    const summarySql    = sq(t.summary);
    const objectivesSql = jsonSq(t.objectives);
    const contentSql    = sq(t.content);
    const examplesSql   = jsonSq(t.examples);
    const mistakesSql   = jsonSq(t.common_mistakes);
    const videosSql     = jsonSq(t.videos);

    // UPSERT: jika (grade,slug) sudah ada → update. Jika belum → insert.
    lines.push(``);
    lines.push(`-- Topik: Kelas ${t.grade} — ${t.title}`);
    lines.push(`INSERT INTO public.topics`);
    lines.push(`  (grade, slug, title, sort_order, summary, content, objectives, examples, common_mistakes, videos)`);
    lines.push(`VALUES`);
    lines.push(`  (${gradeSql}, ${slugSql}, ${titleSql}, ${sortSql}, ${summarySql}, ${contentSql}, ${objectivesSql}, ${examplesSql}, ${mistakesSql}, ${videosSql})`);
    lines.push(`ON CONFLICT (grade, slug) WHERE slug IS NOT NULL`);
    lines.push(`DO UPDATE SET`);
    lines.push(`  title           = EXCLUDED.title,`);
    lines.push(`  sort_order      = EXCLUDED.sort_order,`);
    lines.push(`  summary         = EXCLUDED.summary,`);
    lines.push(`  content         = EXCLUDED.content,`);
    lines.push(`  objectives      = EXCLUDED.objectives,`);
    lines.push(`  examples        = EXCLUDED.examples,`);
    lines.push(`  common_mistakes = EXCLUDED.common_mistakes,`);
    lines.push(`  videos          = EXCLUDED.videos;`);

    allTopics.push({ grade: t.grade, slug: t.slug, questions: t.questions || [] });
  }
}

// ── STEP 3: INSERT questions untuk topik baru ────────────────────────────────
lines.push('');
lines.push('-- ─────────────────────────────────────────────────────────────');
lines.push('-- STEP 3: INSERT questions (hanya untuk topik dari JSON ini)');
lines.push('-- Soal yang sudah ada di DB untuk topik LAMA tidak disentuh.');
lines.push('-- Untuk topik BARU: insert jika belum ada soal (body unik).');
lines.push('-- ─────────────────────────────────────────────────────────────');
lines.push('');
lines.push('-- Kita insert soal hanya jika topic_id cocok dan body belum ada.');
lines.push(`-- Gunakan sub-select untuk ambil topic_id berdasarkan (grade, slug).`);
lines.push('');

for (const { grade, slug, questions } of allTopics) {
  if (!questions || questions.length === 0) continue;

  lines.push(`-- Soal untuk Kelas ${grade} / ${slug}:`);
  for (const q of questions) {
    totalQuestions++;
    const body        = sq(q.body);
    const options     = jsonSq(q.options);
    const answer      = q.answer != null ? q.answer : 0;
    const explanation = sq(q.explanation || null);
    const points      = q.points != null ? q.points : 1;

    lines.push(`INSERT INTO public.questions (topic_id, body, options, answer, explanation, points)`);
    lines.push(`SELECT t.id, ${body}, ${options}, ${answer}, ${explanation}, ${points}`);
    lines.push(`FROM   public.topics t`);
    lines.push(`WHERE  t.grade = ${grade} AND t.slug = ${sq(slug)}`);
    lines.push(`  AND  NOT EXISTS (`);
    lines.push(`    SELECT 1 FROM public.questions q`);
    lines.push(`    WHERE q.topic_id = t.id AND q.body = ${body}`);
    lines.push(`  );`);
  }
  lines.push('');
}

// ── STEP 4: Update sort_order untuk topik lama yang belum punya slug ─────────
lines.push('-- ─────────────────────────────────────────────────────────────');
lines.push('-- STEP 4: Pastikan topik lama mendapat sort_order default');
lines.push('-- ─────────────────────────────────────────────────────────────');
lines.push('');
lines.push('UPDATE public.topics');
lines.push('SET sort_order = id');
lines.push('WHERE sort_order IS NULL;');
lines.push('');

lines.push('COMMIT;');
lines.push('');
lines.push('-- ─────────────────────────────────────────────────────────────');
lines.push('-- Verifikasi (jalankan terpisah setelah COMMIT):');
lines.push('-- SELECT grade, count(*) AS topik, sum((SELECT count(*) FROM questions q WHERE q.topic_id = t.id)) AS soal');
lines.push('-- FROM topics t GROUP BY grade ORDER BY grade;');
lines.push('-- ─────────────────────────────────────────────────────────────');

// ── write output ──────────────────────────────────────────────────────────────

const outDir = path.dirname(OUT_FILE);
if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });

fs.writeFileSync(OUT_FILE, lines.join('\n'), 'utf-8');

const sizeKb = (fs.statSync(OUT_FILE).size / 1024).toFixed(1);
console.log(`\n✅ File SQL berhasil dibuat:`);
console.log(`   ${OUT_FILE}`);
console.log(`   Ukuran: ${sizeKb} KB`);
console.log(`   Topik : ${totalTopics}`);
console.log(`   Soal  : ${totalQuestions}`);
console.log(``);
console.log(`📋 CARA PAKAI:`);
console.log(`   1. Buka Supabase Dashboard → SQL Editor`);
console.log(`   2. Klik "New query"`);
console.log(`   3. Buka file di bawah ini, copy semua isinya:`);
console.log(`      ${OUT_FILE}`);
console.log(`   4. Paste ke SQL Editor → klik RUN`);
console.log(`   5. Tunggu "Success. No rows returned."`);
